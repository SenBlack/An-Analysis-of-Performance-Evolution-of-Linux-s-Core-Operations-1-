#!/usr/bin/env python3
"""Audit the saved LEBench evidence without changing any experiment data.

Run from the repository root:
    python week3/reproducibility_check.py

The script checks the six Week 2 runs and three Week 3 mitigations-off runs,
checks kernel labels and test-row consistency, and writes a Markdown report
with SHA-256 hashes for traceability. It does not rerun LEBench.
"""
from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WEEK2 = ROOT / "week2" / "three-runs"
WEEK3 = ROOT / "week3" / "mitigations-off"
REPORT = ROOT / "week3" / "reproducibility_report.md"
WEEK2_KERNELS = ("5.15.0-203-generic", "6.8.0-138-generic")
WEEK3_KERNEL = "5.15.0-203-generic"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def inspect_log(path: Path, expected_kernel: str) -> tuple[list[str], str]:
    if not path.is_file():
        raise ValueError(f"missing file: {path.relative_to(ROOT)}")
    lines = path.read_text(encoding="utf-8").splitlines()
    kernel = None
    tests: list[str] = []
    for raw in lines:
        line = raw.strip()
        if not line:
            continue
        parts = [part.strip() for part in line.split(",")]
        if parts[0].startswith("Test Name"):
            if len(parts) < 2:
                raise ValueError(f"malformed Test Name row: {path.name}")
            kernel = parts[1]
            continue
        if parts[0].endswith(":") and len(parts) >= 2 and parts[1]:
            label = parts[0][:-1].strip()
            match = re.match(r"^(.*?)\s+(kbest|average)$", label)
            if match and match.group(2) == "kbest":
                tests.append(" ".join(match.group(1).split()))
    if kernel != expected_kernel:
        raise ValueError(f"{path.name}: kernel label {kernel!r}, expected {expected_kernel!r}")
    if not tests:
        raise ValueError(f"{path.name}: no kbest test rows found")
    if len(tests) != len(set(tests)):
        raise ValueError(f"{path.name}: duplicate kbest test labels")
    return tests, sha256(path)


def main() -> int:
    records: list[tuple[str, str, int]] = []
    baseline_tests: list[str] | None = None
    checks: list[str] = []

    for kernel in WEEK2_KERNELS:
        for run in (1, 2, 3):
            path = WEEK2 / f"{kernel}-run{run}.csv"
            tests, digest = inspect_log(path, kernel)
            if baseline_tests is None:
                baseline_tests = tests
            elif tests != baseline_tests:
                raise ValueError(f"{path.name}: test names/order differ from other Week 2 runs")
            records.append((str(path.relative_to(ROOT)).replace("\\", "/"), digest, len(tests)))
        checks.append(f"- PASS: Week 2 {kernel}: three logs, kernel labels and test order consistent ({len(baseline_tests or [])} tests).")

    for run in (1, 2, 3):
        path = WEEK3 / f"{WEEK3_KERNEL}-mitigations-off-run{run}.csv"
        tests, digest = inspect_log(path, WEEK3_KERNEL)
        if baseline_tests is not None and tests != baseline_tests:
            raise ValueError(f"{path.name}: test names/order differ from Week 2 baseline")
        records.append((str(path.relative_to(ROOT)).replace("\\", "/"), digest, len(tests)))
    checks.append(f"- PASS: Week 3 mitigations-off: three logs, kernel labels and test order consistent ({len(baseline_tests or [])} tests).")

    cmdline = WEEK3 / "cmdline.txt"
    if not cmdline.is_file() or "mitigations=off" not in cmdline.read_text(encoding="utf-8"):
        raise ValueError("Week 3 cmdline.txt is missing or does not record mitigations=off")
    checks.append("- PASS: Week 3 cmdline.txt records `mitigations=off`.")

    wallclock = WEEK3 / "wallclock.txt"
    if not wallclock.is_file():
        raise ValueError("Week 3 wallclock.txt is missing")
    wall_lines = [line for line in wallclock.read_text(encoding="utf-8").splitlines() if line.strip()]
    if len(wall_lines) != 3:
        raise ValueError(f"Week 3 wallclock.txt has {len(wall_lines)} entries; expected 3")
    checks.append("- PASS: Week 3 wallclock.txt contains three run-time records.")

    output = [
        "# Reproducibility audit (Week 3)", "",
        "Generated by `python week3/reproducibility_check.py`.",
        "This is a file-integrity and metadata consistency check, not a new benchmark run.", "",
        "## Checks", "", *checks, "",
        "## Input log fingerprints", "",
        "| File | SHA-256 | kbest rows |", "| --- | --- | ---: |",
    ]
    output.extend(f"| `{name}` | `{digest}` | {count} |" for name, digest, count in records)
    output += ["", "## Scope and limitations", "",
        "- The script verifies that the archived logs exist, identify the expected kernel, and contain matching `kbest` test names in the same order.",
        "- It verifies the recorded Week 3 boot parameter and the presence of three wall-clock entries.",
        "- SHA-256 values identify the exact archived input files used for this audit.",
        "- This check does not prove the benchmark was run on the claimed machine, independently authenticate screenshots, or reproduce the measurements.",
        "- It does not modify CSV logs, regenerate earlier summaries, install kernels, or execute LEBench.", ""]
    REPORT.write_text("\n".join(output), encoding="utf-8")
    print("\n".join(checks))
    print(f"Wrote {REPORT.relative_to(ROOT)} ({len(records)} input logs fingerprinted).")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        raise SystemExit(1)
